TITLE = "Understanding Climate Change"

BODY = """What is climate change?

Climate change refers to long-term shifts in temperatures and weather \
patterns. While the climate has always changed naturally, scientific \
measurements since the late 1800s show the planet has warmed at an \
unusually fast pace, and the leading driver is human activity.

The greenhouse effect

Earth's atmosphere contains gases - mainly carbon dioxide, methane, and \
water vapor - that trap heat from the sun, similar to how glass traps \
heat inside a greenhouse. This effect is natural and necessary; without \
it, Earth would be far too cold for life. The problem is that burning \
coal, oil, and gas for energy, along with deforestation and industrial \
farming, has sharply increased the amount of these gases in the \
atmosphere, trapping more heat than before.

What's changing

Average global temperatures have risen by more than 1 degree Celsius \
since the pre-industrial era. That may sound small, but it's enough to \
shift weather patterns worldwide. Scientists link the warming trend to \
more frequent and intense heatwaves, stronger storms, longer droughts \
in some regions, heavier rainfall and flooding in others, melting \
glaciers and polar ice, and rising sea levels that threaten coastal \
communities.

Why it matters

These changes affect food and water supplies, human health, wildlife \
habitats, and local economies. Some regions face more immediate risk \
than others, but the effects are global and interconnected - a drought \
in one region can affect food prices worldwide.

What can help

Scientists and policymakers point to several ways to slow climate \
change: shifting to renewable energy sources like solar, wind, and \
hydro power; improving energy efficiency in homes, transport, and \
industry; protecting and restoring forests, which absorb carbon \
dioxide; and reducing food waste, since decomposing waste releases \
methane. Individual choices - like conserving energy, reducing waste, \
and supporting sustainable practices - add up when combined with \
larger changes in energy and industry.

Ready to put what you've learned into practice? Try the games below - \
they'll test your knowledge and challenge you to make climate-smart \
choices."""
